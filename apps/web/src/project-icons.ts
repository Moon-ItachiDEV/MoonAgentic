export type ProjectIconName = keyof typeof PROJECT_ICONS;

/** What a project keeps in its icon when it wears one of these. */
export const PROJECT_ICON_PREFIX = "i:";

/** The icon of these a project's icon names, or nothing when it is an emoji or letters. */
export function projectIconName(icon: string | undefined): ProjectIconName | undefined {
  if (!icon?.startsWith(PROJECT_ICON_PREFIX)) return undefined;
  const name = icon.slice(PROJECT_ICON_PREFIX.length);
  return Object.hasOwn(PROJECT_ICONS, name) ? (name as ProjectIconName) : undefined;
}

/** Lower case and without accents, so « cle » finds « Clé ». */
const plain = (text: string) =>
  text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();

/** The icons whose French name or own name holds what is searched, in their order. */
export function findProjectIcons(query: string): ProjectIconName[] {
  const q = plain(query);
  const names = Object.keys(PROJECT_ICONS) as ProjectIconName[];
  if (!q) return names;
  return names.filter((name) => plain(`${PROJECT_ICONS[name][0]} ${name}`).includes(q));
}

/** These icons as symbols of the hidden sprite: `#pi-<name>`. */
export const PROJECT_SPRITE = Object.entries(PROJECT_ICONS)
  .map(
    ([name, [, body]]) =>
      `<symbol id="pi-${name}" viewBox="0 0 24 24"><g fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round">${body}</g></symbol>`,
  )
  .join("");
